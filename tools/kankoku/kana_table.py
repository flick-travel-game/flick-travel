#!/usr/bin/env python3
"""発音どおりの ハングル(pron)→ 読みの ひらがな。**ここ 1か所の 表だけで 作る**(読みを 手で 書かない)
けいくん決定 2026-10-10「まずA、あとでB」(打つのは 読みの ひらがな)

決まり(けいくんに 見せて 決めた 表):
  ・パッチム(下の 字): ㄱ → く / ㄴ → ん / ㄷ・ㅅ → っ / ㄹ → る / ㅁ → む / ㅂ → ぷ / ㅇ → ん
  ・ㅓ と ㅗ は どちらも お、ㅡ と ㅜ は どちらも う、ㅐ と ㅔ は どちらも え
  ・ㄱ ㄷ ㅂ ㅈ は 語の はじめと 音の かたい パッチムの あとは か・た・ぱ・ちゃ、それ以外(母音・ㄴㄹㅁㅇ の あと)は が・だ・ば・じゃ
    (打つときは どちらでも 正解。kankoku.js の norm が 濁点を そろえる)
  ・濃音(ㄲ ㄸ ㅃ ㅆ ㅉ)は 母音の あとなら 前に っ(오빠 → おっぱ)。っ は 打たなくても 正解
  ・pron は **発音どおり**(連音化・鼻音化・濃音化を すませた 形)を 書く。この 表は 字を そのまま かなに する だけ
    python3 tools/kankoku/kana_table.py 안녕하세요 한구거   # ためす"""
import sys

CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
JUNG = ["ㅏ", "ㅐ", "ㅑ", "ㅒ", "ㅓ", "ㅔ", "ㅕ", "ㅖ", "ㅗ", "ㅘ", "ㅙ", "ㅚ", "ㅛ", "ㅜ", "ㅝ", "ㅞ", "ㅟ", "ㅠ", "ㅡ", "ㅢ", "ㅣ"]
JONG = ["", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ", "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"]

# パッチムの かな(代表音 7つに まとめる)
FINAL = {"": ""}
for js, k in (("ㄱㄲㄳㄺㅋ", "く"), ("ㄴㄵㄶ", "ん"), ("ㄷㅅㅆㅈㅊㅌㅎ", "っ"), ("ㄹㄼㄽㄾㅀ", "る"), ("ㅁㄻ", "む"), ("ㅂㅄㄿㅍ", "ぷ"), ("ㅇ", "ん")):
    for j in js: FINAL[j] = k
# 音を にごらせない パッチム(この あとの ㄱㄷㅂㅈ は か・た・ぱ・ちゃ のまま)
HARD = {"ㄱ", "ㄲ", "ㄳ", "ㄺ", "ㅋ", "ㄷ", "ㅅ", "ㅆ", "ㅈ", "ㅊ", "ㅌ", "ㅎ", "ㅂ", "ㅄ", "ㄿ", "ㅍ"}

# 母音 → (a/i/u/e/o の どれか, y が つくか, w が つくか)
V = {"ㅏ": ("a", 0, 0), "ㅐ": ("e", 0, 0), "ㅑ": ("a", 1, 0), "ㅒ": ("e", 1, 0), "ㅓ": ("o", 0, 0), "ㅔ": ("e", 0, 0), "ㅕ": ("o", 1, 0), "ㅖ": ("e", 1, 0),
     "ㅗ": ("o", 0, 0), "ㅘ": ("a", 0, 1), "ㅙ": ("e", 0, 1), "ㅚ": ("e", 0, 1), "ㅛ": ("o", 1, 0), "ㅜ": ("u", 0, 0), "ㅝ": ("o", 0, 1), "ㅞ": ("e", 0, 1),
     "ㅟ": ("i", 0, 1), "ㅠ": ("u", 1, 0), "ㅡ": ("u", 0, 0), "ㅢ": ("ui", 0, 0), "ㅣ": ("i", 0, 0)}
IDX = {"a": 0, "i": 1, "u": 2, "e": 3, "o": 4}
SMALL_Y = {"a": "ゃ", "u": "ゅ", "o": "ょ", "e": "ぇ"}
SMALL_V = {"a": "ぁ", "i": "ぃ", "u": "ぅ", "e": "ぇ", "o": "ぉ"}
# 行(a i u e o)。にごる 行は 2つめ
ROW = {
    "k": ("かきくけこ", "がぎぐげご"), "n": ("なにぬねの",), "t": ("た", "てぃ", "とぅ", "て", "と"), "d": ("だ", "でぃ", "どぅ", "で", "ど"),
    "r": ("らりるれろ",), "m": ("まみむめも",), "p": ("ぱぴぷぺぽ", "ばびぶべぼ"), "s": ("さしすせそ",), "": ("あいうえお",),
    "ch": ("ちゃ", "ち", "ちゅ", "ちぇ", "ちょ"), "j": ("じゃ", "じ", "じゅ", "じぇ", "じょ"), "h": ("はひふへほ",),
}
CON = {"ㄱ": ("k", 1), "ㄲ": ("k", 0), "ㄴ": ("n", 0), "ㄷ": ("t", 1), "ㄸ": ("t", 0), "ㄹ": ("r", 0), "ㅁ": ("m", 0), "ㅂ": ("p", 1), "ㅃ": ("p", 0),
       "ㅅ": ("s", 0), "ㅆ": ("s", 0), "ㅇ": ("", 0), "ㅈ": ("ch", 1), "ㅉ": ("ch", 0), "ㅊ": ("ch", 0), "ㅋ": ("k", 0), "ㅌ": ("t", 0), "ㅍ": ("p", 0), "ㅎ": ("h", 0)}
TENSE = set("ㄲㄸㅃㅆㅉ")


def cell(row, vowel):
    """行 + a/i/u/e/o → かな 1つ"""
    r = ROW[row]
    if len(r) == 5: return r[IDX[vowel]]
    return r[0][IDX[vowel]]


def voiced(row):
    return {"k": "k2", "t": "d", "p": "p2", "ch": "j"}.get(row, row)


def syl(c, v, voice):
    """子音 c(ㄱ…)+ 母音 v(ㅏ…)→ かな"""
    row, can = CON[c]
    if voice and can:
        if row in ("k", "p"):
            base = lambda vv: ROW[row][1][IDX[vv]]
        else:
            row = voiced(row); base = lambda vv: cell(row, vv)
    else:
        base = lambda vv: cell(row, vv)
    a, y, w = V[v]
    if a == "ui":  # ㅢ: 語の はじめ(ㅇ)は うい、子音の あとは い
        return "うい" if row == "" else base("i")
    if row == "":
        if w: return {"a": "わ", "o": "うぉ", "e": "うぇ", "i": "うぃ"}[a]
        if y: return {"a": "や", "u": "ゆ", "o": "よ", "e": "いぇ"}[a]
        return base(a)
    if w:  # 과 → くぁ / 화 → ふぁ
        return base("u") + SMALL_V[a]
    if y:
        if row in ("ch", "j"):  # 쟈 → ちゃ(ㅈ・ㅊ に y は 聞こえない)
            return base(a)
        if a == "e": return base("e")  # 계 → け
        if row == "s": return {"a": "しゃ", "u": "しゅ", "o": "しょ"}[a]
        return base("i") + SMALL_Y[a]
    return base(a)


def kana(pron):
    """発音どおりの ハングル → ひらがな。空白は 空白のまま、ハングル以外の 字(? ! など)は そのまま"""
    out = []; prev_final = None  # None = 語の はじめ
    for ch in pron:
        o = ord(ch) - 0xAC00
        if not 0 <= o < 11172:
            out.append(ch); prev_final = None if ch in " ,.?!…~" else prev_final; continue
        c, v, f = CHO[o // 588], JUNG[(o % 588) // 28], JONG[o % 28]
        voice = prev_final is not None and prev_final not in HARD
        s = syl(c, v, voice)
        if c in TENSE and prev_final == "": s = "っ" + s  # 오빠 → おっぱ
        out.append(s + FINAL[f]); prev_final = f
    return "".join(out)


def is_hangul_text(s):
    return any(0xAC00 <= ord(c) < 0xAC00 + 11172 for c in s)


if __name__ == "__main__":
    for w in sys.argv[1:] or ["안녕하세요", "한구거", "감사함니다", "김치", "오빠", "가치", "학꾜", "서울", "괜차나요", "의사", "회의", "계속", "뭐", "왜요", "사랑해", "밥", "맛있써요", "마시써요", "쳐다보다", "주세요", "뒤", "예", "위"]:
        print(w, "→", kana(w))
